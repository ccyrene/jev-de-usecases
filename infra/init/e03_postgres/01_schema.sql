-- E03 base schema: synthetic shop database (27 tables). All data is fictional.
DROP SCHEMA IF EXISTS shop CASCADE;
CREATE SCHEMA shop;
SET search_path = shop;

CREATE TABLE categories (
  category_id int GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  parent_id int,
  CONSTRAINT pk_categories PRIMARY KEY (category_id),
  CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE customers (
  customer_id bigint GENERATED BY DEFAULT AS IDENTITY,
  email text NOT NULL,
  full_name text NOT NULL,
  phone text,
  country_code char(2) NOT NULL DEFAULT 'TH',
  status text NOT NULL DEFAULT 'active',
  loyalty_points int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT timestamptz '2026-01-01 00:00:00+00',
  legacy_segment text,
  CONSTRAINT pk_customers PRIMARY KEY (customer_id),
  CONSTRAINT uq_customers_email UNIQUE (email),
  CONSTRAINT ck_customers_status CHECK (status IN ('active', 'suspended', 'closed'))
);
CREATE INDEX ix_customers_country ON customers (country_code);

CREATE TABLE customer_addresses (
  address_id bigint GENERATED BY DEFAULT AS IDENTITY,
  customer_id bigint NOT NULL,
  line1 text NOT NULL,
  city text,
  postal_code varchar(10),
  is_default boolean NOT NULL DEFAULT false,
  legacy_region text,
  CONSTRAINT pk_customer_addresses PRIMARY KEY (address_id),
  CONSTRAINT fk_customer_addresses_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id)
);
CREATE INDEX ix_customer_addresses_customer ON customer_addresses (customer_id);

CREATE TABLE suppliers (
  supplier_id int GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  contact_email text,
  lead_time_days smallint NOT NULL DEFAULT 7,
  legacy_fax text,
  CONSTRAINT pk_suppliers PRIMARY KEY (supplier_id)
);

CREATE TABLE products (
  product_id bigint GENERATED BY DEFAULT AS IDENTITY,
  sku text NOT NULL,
  name text NOT NULL,
  category_id int,
  supplier_id int,
  unit_price numeric(12,2) NOT NULL,
  weight_kg numeric(8,3),
  is_active boolean NOT NULL DEFAULT true,
  legacy_code text,
  CONSTRAINT pk_products PRIMARY KEY (product_id),
  CONSTRAINT uq_products_sku UNIQUE (sku),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (category_id),
  CONSTRAINT fk_products_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (supplier_id)
);
CREATE INDEX ix_products_category ON products (category_id);
CREATE INDEX ix_products_active ON products (is_active);

CREATE TABLE warehouses (
  warehouse_id int GENERATED BY DEFAULT AS IDENTITY,
  code text NOT NULL,
  city text,
  capacity_units int,
  CONSTRAINT pk_warehouses PRIMARY KEY (warehouse_id),
  CONSTRAINT uq_warehouses_code UNIQUE (code)
);

CREATE TABLE inventory (
  inventory_id bigint GENERATED BY DEFAULT AS IDENTITY,
  product_id bigint NOT NULL,
  warehouse_id int NOT NULL,
  qty_on_hand int NOT NULL,
  reorder_level int NOT NULL DEFAULT 10,
  updated_at timestamptz NOT NULL DEFAULT timestamptz '2026-01-01 00:00:00+00',
  legacy_bin text,
  CONSTRAINT pk_inventory PRIMARY KEY (inventory_id),
  CONSTRAINT uq_inventory_product_wh UNIQUE (product_id, warehouse_id),
  CONSTRAINT ck_inventory_qty CHECK (qty_on_hand >= 0),
  CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT fk_inventory_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses (warehouse_id)
);
CREATE INDEX ix_inventory_warehouse ON inventory (warehouse_id);

CREATE TABLE inventory_movements (
  movement_id bigint GENERATED BY DEFAULT AS IDENTITY,
  product_id bigint NOT NULL,
  warehouse_id int NOT NULL,
  delta int NOT NULL,
  reason text NOT NULL,
  moved_at timestamptz NOT NULL DEFAULT timestamptz '2026-01-01 00:00:00+00',
  CONSTRAINT pk_inventory_movements PRIMARY KEY (movement_id),
  CONSTRAINT fk_movements_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT fk_movements_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouses (warehouse_id)
);
CREATE INDEX ix_movements_product ON inventory_movements (product_id);

CREATE TABLE purchase_orders (
  po_id bigint GENERATED BY DEFAULT AS IDENTITY,
  supplier_id int NOT NULL,
  status text NOT NULL,
  ordered_at timestamptz NOT NULL,
  total_amount numeric(12,2) NOT NULL,
  CONSTRAINT pk_purchase_orders PRIMARY KEY (po_id),
  CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (supplier_id)
);

CREATE TABLE purchase_order_lines (
  po_line_id bigint GENERATED BY DEFAULT AS IDENTITY,
  po_id bigint NOT NULL,
  product_id bigint NOT NULL,
  qty int NOT NULL,
  unit_cost numeric(12,2) NOT NULL,
  CONSTRAINT pk_purchase_order_lines PRIMARY KEY (po_line_id),
  CONSTRAINT fk_po_lines_po FOREIGN KEY (po_id) REFERENCES purchase_orders (po_id),
  CONSTRAINT fk_po_lines_product FOREIGN KEY (product_id) REFERENCES products (product_id)
);

CREATE TABLE orders (
  order_id bigint GENERATED BY DEFAULT AS IDENTITY,
  customer_id bigint NOT NULL,
  status text NOT NULL,
  order_total numeric(12,2) NOT NULL,
  currency char(3) NOT NULL DEFAULT 'THB',
  placed_at timestamptz NOT NULL,
  channel text,
  internal_note text,
  CONSTRAINT pk_orders PRIMARY KEY (order_id),
  CONSTRAINT ck_orders_status CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled')),
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id)
);
CREATE INDEX ix_orders_customer ON orders (customer_id);
CREATE INDEX ix_orders_placed_at ON orders (placed_at);
CREATE INDEX ix_orders_status ON orders (status);

CREATE TABLE order_items (
  order_item_id bigint GENERATED BY DEFAULT AS IDENTITY,
  order_id bigint NOT NULL,
  product_id bigint NOT NULL,
  quantity int NOT NULL,
  unit_price numeric(12,2) NOT NULL,
  discount_pct numeric(5,2) NOT NULL DEFAULT 0,
  CONSTRAINT pk_order_items PRIMARY KEY (order_item_id),
  CONSTRAINT ck_order_items_qty CHECK (quantity > 0),
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
  CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (product_id)
);
CREATE INDEX ix_order_items_order ON order_items (order_id);

CREATE TABLE shipments (
  shipment_id bigint GENERATED BY DEFAULT AS IDENTITY,
  order_id bigint NOT NULL,
  carrier text NOT NULL,
  tracking_no text,
  shipped_at timestamptz,
  delivered_at timestamptz,
  CONSTRAINT pk_shipments PRIMARY KEY (shipment_id),
  CONSTRAINT fk_shipments_order FOREIGN KEY (order_id) REFERENCES orders (order_id)
);
CREATE INDEX ix_shipments_order ON shipments (order_id);

CREATE TABLE payment_methods (
  method_id int GENERATED BY DEFAULT AS IDENTITY,
  code text NOT NULL,
  label text,
  CONSTRAINT pk_payment_methods PRIMARY KEY (method_id),
  CONSTRAINT uq_payment_methods_code UNIQUE (code)
);

CREATE TABLE payments (
  payment_id bigint GENERATED BY DEFAULT AS IDENTITY,
  order_id bigint NOT NULL,
  method text NOT NULL,
  amount numeric(12,2) NOT NULL,
  currency char(3) NOT NULL DEFAULT 'THB',
  status text NOT NULL,
  paid_at timestamptz,
  reference text,
  CONSTRAINT pk_payments PRIMARY KEY (payment_id),
  CONSTRAINT uq_payments_reference UNIQUE (reference),
  CONSTRAINT ck_payments_status CHECK (status IN ('authorized', 'captured', 'failed', 'refunded')),
  CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (order_id)
);
CREATE INDEX ix_payments_order ON payments (order_id);
CREATE INDEX ix_payments_status ON payments (status);

CREATE TABLE refunds (
  refund_id bigint GENERATED BY DEFAULT AS IDENTITY,
  payment_id bigint NOT NULL,
  amount numeric(12,2) NOT NULL,
  reason text,
  refunded_at timestamptz NOT NULL,
  CONSTRAINT pk_refunds PRIMARY KEY (refund_id),
  CONSTRAINT fk_refunds_payment FOREIGN KEY (payment_id) REFERENCES payments (payment_id)
);
CREATE INDEX ix_refunds_payment ON refunds (payment_id);

CREATE TABLE coupons (
  coupon_id int GENERATED BY DEFAULT AS IDENTITY,
  code text NOT NULL,
  discount_pct numeric(5,2) NOT NULL,
  valid_until date,
  CONSTRAINT pk_coupons PRIMARY KEY (coupon_id),
  CONSTRAINT uq_coupons_code UNIQUE (code)
);

CREATE TABLE order_coupons (
  order_id bigint NOT NULL,
  coupon_id int NOT NULL,
  CONSTRAINT pk_order_coupons PRIMARY KEY (order_id, coupon_id),
  CONSTRAINT fk_order_coupons_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
  CONSTRAINT fk_order_coupons_coupon FOREIGN KEY (coupon_id) REFERENCES coupons (coupon_id)
);

CREATE TABLE reviews (
  review_id bigint GENERATED BY DEFAULT AS IDENTITY,
  product_id bigint NOT NULL,
  customer_id bigint NOT NULL,
  rating smallint NOT NULL,
  body text,
  created_at timestamptz NOT NULL DEFAULT timestamptz '2026-01-01 00:00:00+00',
  CONSTRAINT pk_reviews PRIMARY KEY (review_id),
  CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
  CONSTRAINT fk_reviews_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT fk_reviews_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id)
);
CREATE INDEX ix_reviews_product ON reviews (product_id);

